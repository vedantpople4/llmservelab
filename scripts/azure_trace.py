"""Cut replay windows from the Azure LLM inference trace (2023, conversation) for Phase 7.

Downloads `AzureLLMInferenceTrace_conv.csv` from the Azure Public Dataset (CC BY 4.0), drops
requests that do not fit `--max-model-len`, splits the rest into consecutive blocks of
`--requests`, and writes the steadiest and the burstiest block (lowest and highest coefficient of
variation of inter-arrival gaps) as trace CSVs under `configs/traces/`, offsets rebased to 0.
It also writes the per-class median output length of every request outside those two blocks to
`configs/output_priors/azure-conv.json`, for the `class_prior` estimator.

    uv run python scripts/azure_trace.py
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import urllib.request
from datetime import datetime
from pathlib import Path

import numpy as np

URL = (
    "https://raw.githubusercontent.com/Azure/AzurePublicDataset/master/data/"
    "AzureLLMInferenceTrace_conv.csv"
)
ROOT = Path(__file__).resolve().parent.parent
ATTRIBUTION = (
    "Azure LLM inference trace 2023 (conversation), Azure Public Dataset, licensed CC BY 4.0, "
    "https://github.com/Azure/AzurePublicDataset. Patel et al., Splitwise, ISCA 2024."
)
# The classes a trace request belongs to, first match wins. Suites that replay these windows
# use the same thresholds as `match` rules.
LONG_CONTEXT_PROMPT_MIN = 2048
GENERATION_HEAVY_OUTPUT_MIN = 256


def label(prompt: int, output: int) -> str:
    if prompt >= LONG_CONTEXT_PROMPT_MIN:
        return "long_context"
    if output >= GENERATION_HEAVY_OUTPUT_MIN:
        return "generation_heavy"
    return "interactive"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--requests", type=int, default=150)
    parser.add_argument("--max-model-len", type=int, default=10240)
    args = parser.parse_args()

    with urllib.request.urlopen(URL, timeout=60) as response:
        rows = list(csv.DictReader(io.StringIO(response.read().decode())))
    times = np.array(
        [datetime.fromisoformat(r["TIMESTAMP"][:26]).timestamp() for r in rows], dtype=np.float64
    )
    prompts = np.array([int(r["ContextTokens"]) for r in rows], dtype=np.int64)
    outputs = np.array([int(r["GeneratedTokens"]) for r in rows], dtype=np.int64)
    order = np.argsort(times, kind="stable")
    times, prompts, outputs = times[order], prompts[order], outputs[order]
    fits = (prompts + outputs <= args.max_model_len) & (prompts >= 1) & (outputs >= 1)
    dropped = int((~fits).sum())
    times, prompts, outputs = times[fits], prompts[fits], outputs[fits]

    n = args.requests
    blocks = [slice(i, i + n) for i in range(0, len(times) - n + 1, n)]
    cv = [float(np.std(np.diff(times[b])) / np.mean(np.diff(times[b]))) for b in blocks]
    picks = {"steady": blocks[int(np.argmin(cv))], "bursty": blocks[int(np.argmax(cv))]}

    out_dir = ROOT / "configs" / "traces"
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, block in picks.items():
        offsets = times[block] - times[block][0]
        span = float(offsets[-1])
        path = out_dir / f"azure-conv-2023-{name}.csv"
        lines = [
            f"# {ATTRIBUTION}",
            f"# Generated by scripts/azure_trace.py: requests {block.start} to {block.stop - 1} "
            f"of {len(times)} after dropping {dropped} longer than {args.max_model_len} tokens.",
            f"# {n} requests over {span:.1f} s ({n / span:.2f} req/s), inter-arrival CV "
            f"{cv[blocks.index(block)]:.2f}.",
            "offset_s,prompt_tokens,output_tokens",
            *(
                f"{o:.4f},{p},{g}"
                for o, p, g in zip(offsets, prompts[block], outputs[block], strict=True)
            ),
        ]
        path.write_text("\n".join(lines) + "\n")
        print(f"wrote {path.relative_to(ROOT)}: {n} requests, {n / span:.2f} req/s")

    held = np.ones(len(times), dtype=bool)
    for block in picks.values():
        held[block] = False
    labels = np.array([label(int(p), int(g)) for p, g in zip(prompts, outputs, strict=True)])
    prior = {
        cls: int(np.median(outputs[held & (labels == cls)]))
        for cls in ("generation_heavy", "interactive", "long_context")
    }
    prior_path = ROOT / "configs" / "output_priors" / "azure-conv.json"
    prior_path.write_text(json.dumps(prior, indent=2, sort_keys=True) + "\n")
    print(f"wrote {prior_path.relative_to(ROOT)}: {prior}")


if __name__ == "__main__":
    main()
